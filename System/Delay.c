#include "stm32f10x.h"

/*==============================================================================
 * Delay.c —— 延时函数（让程序"停一下"）
 *
 * 【原理】
 *   用 STM32 的 SysTick 系统滴答定时器做倒计时：
 *   设定一个计数值，让它从那个数减到 0，期间程序就"忙等"（什么都不干，干等）。
 *   因为主频是 72MHz（每秒 7200 万个时钟周期），
 *   所以延时 1 微秒 = 数 72 个周期，LOAD = 72*xus 就是这个意思。
 *
 * 【重要提醒】
 *   这种延时是"阻塞式"的：延时期间 CPU 一直在空转，做不了别的事。
 *   所以在"要同时干很多事"的主循环里，别用长延时；
 *   它适合在"等一个外设稳定"（比如等 OLED 上电、等指纹模块应答）这种短场景。
 *
 * 【与低功耗的关系】
 *   SysTick 依赖主时钟（HCLK），进入 Stop 低功耗模式后主时钟停了，
 *   延时就不走了；醒来恢复时钟后延时才恢复正常（见 LowPower.c）。
 *============================================================================*/

/**
  * @brief  微秒级延时（阻塞式）
  * @param  xus 延时时长，范围：0~233015（微秒）
  * @retval 无
  * @note   72*xus 是因为主频 72MHz，1 微秒走 72 个时钟周期。
  */
void Delay_us(uint32_t xus)
{
	SysTick->LOAD = 72 * xus;				//设置定时器重装值
	SysTick->VAL = 0x00;					//清空当前计数值
	SysTick->CTRL = 0x00000005;				//设置时钟源为HCLK，启动定时器
	while(!(SysTick->CTRL & 0x00010000));	//等待计数到0
	SysTick->CTRL = 0x00000004;				//关闭定时器
}

/**
  * @brief  毫秒级延时
  * @param  xms 延时时长，范围：0~4294967295
  * @retval 无
  */
void Delay_ms(uint32_t xms)
{
	while(xms--)
	{
		Delay_us(1000);
	}
}
 
/**
  * @brief  秒级延时
  * @param  xs 延时时长，范围：0~4294967295
  * @retval 无
  */
void Delay_s(uint32_t xs)
{
	while(xs--)
	{
		Delay_ms(1000);
	}
} 
